"""Build and validate cases: gold + exactly one injected misconfiguration (CLAUDE.md §7).

cases/<case_id>/manifests.yaml   what the repairer sees
cases/<case_id>/meta.json        type, fix class, service, target rules, reference fix (analysis only, never in a prompt)
cases/<case_id>/validation.json  evidence that the case is valid
"""

from __future__ import annotations

import hashlib
import json
import time
from datetime import datetime, timezone
from pathlib import Path

import yaml

from harness.checks import intent, k6, scanners
from harness.deploy import kind
from harness.gold import NAMESPACE, OUT as GOLD_MANIFEST, build, harden, write
from harness.injectors import REGISTRY

CASES = kind.ROOT / "cases"
GOLD_SCAN = kind.ROOT / "app" / "gold" / "scan.json"


def case_id(type_: str, service: str) -> str:
    return f"{type_}-{service}"


def gold_findings(refresh: bool = False) -> list[dict]:
    gold_sha = hashlib.sha256(GOLD_MANIFEST.read_bytes()).hexdigest()
    if GOLD_SCAN.exists() and not refresh:
        cached = json.loads(GOLD_SCAN.read_text(encoding="utf-8"))
        if cached["gold_sha256"] == gold_sha and cached["scanners"] == scanners.VERSIONS:
            return cached["findings"]
    findings = scanners.scan(GOLD_MANIFEST)
    GOLD_SCAN.write_text(json.dumps({"gold_sha256": gold_sha, "scanners": scanners.VERSIONS, "findings": findings},
                                    indent=1), encoding="utf-8", newline="\n")
    return findings


def build_case(type_: str, service: str) -> Path:
    spec = REGISTRY[type_]
    docs = spec.inject(harden(build()), service)
    d = CASES / case_id(type_, service)
    d.mkdir(parents=True, exist_ok=True)
    manifest = write(docs, d / "manifests.yaml")
    manifest.write_text(manifest.read_text(encoding="utf-8").replace(
        "# GENERATED by `harness gold-build`", f"# GENERATED by `harness case-build {type_} {service}`"),
        encoding="utf-8", newline="\n")
    svc_obj = next((x for x in docs if x.get("kind") == "Service" and x["metadata"]["name"] == service), None)
    meta = {
        "case_id": case_id(type_, service),
        "service_port": svc_obj["spec"]["ports"][0]["port"] if svc_obj else None,
        "type": type_,
        "fix_class": spec.fix_class,
        "service": service,
        "reference_fix": spec.reference_fix,
        "target_rules": list(spec.target_rules),
        "coupled_rules": list(spec.coupled_rules),
        **spec.meta_extra,
        "gold_sha256": hashlib.sha256(GOLD_MANIFEST.read_bytes()).hexdigest(),
        "case_sha256": hashlib.sha256(manifest.read_bytes()).hexdigest(),
    }
    (d / "meta.json").write_text(json.dumps(meta, indent=1), encoding="utf-8", newline="\n")
    return d


def v4_flags(l7: dict) -> bool:
    """V4 (D-021): L7 flags the injected case. The runtime probe must have produced data AND show the intent violated
    (a probe that returns nothing must never count as 'flagged'); the static check must flag it too, unless the type
    has no static policy (netpol: the intent is about traffic)."""
    if not l7:
        return False
    static = l7.get("static", {})
    static_flags = bool(static.get("skipped")) or not static.get("ok", True)
    return bool(l7.get("runtime", {}).get("ok", False)) and not l7.get("runtime_ok", True) and static_flags


def validate_case(d: Path, deploy: bool = True) -> dict:
    """V1: new findings appear on the case; V2: gold has none of them; V3: the case deploys and the app works."""
    meta = json.loads((d / "meta.json").read_text(encoding="utf-8"))
    gold = scanners.keys(gold_findings())
    case_f = scanners.scan(d / "manifests.yaml")
    new = sorted(scanners.keys(case_f) - gold)
    removed = sorted(gold - scanners.keys(case_f))
    res: dict = {
        "case_id": meta["case_id"],
        "validated": datetime.now(timezone.utc).isoformat(),
        "scanners": scanners.VERSIONS,
        "new_findings": new,
        "gold_findings_lost": removed,
        "v1_flagged": bool(new),
        # every declared target and coupled rule must be among the new findings, and nothing else may be
        "v1_targets_present": all(any(k.startswith(r + ":") for k in new) for r in meta["target_rules"]),
        "unexpected_new_findings": [k for k in new if not any(k.startswith(r + ":")
                                    for r in meta["target_rules"] + meta["coupled_rules"])],
        "v2_gold_clean_for_targets": not (set(new) & gold),
    }
    if deploy:
        ctx = f"sbb-val-{meta['case_id']}"[:40]
        try:
            kind.create_cluster(ctx)
            kind.kubectl(ctx, "create", "namespace", NAMESPACE)
            dry = kind.kubectl(ctx, "apply", "--dry-run=server", "-f", str(d / "manifests.yaml"), check=False)
            res["dry_run_ok"] = dry.returncode == 0
            t0 = time.perf_counter()
            kind.kubectl(ctx, "apply", "-f", str(d / "manifests.yaml"), check=False)
            w = kind.kubectl(ctx, "-n", NAMESPACE, "wait", "deploy", "--all", "--for=condition=Available",
                             "--timeout=300s", check=False, timeout=400)
            res["ready_s"] = round(time.perf_counter() - t0, 1)
            res["all_available"] = w.returncode == 0
            if res["all_available"]:
                f = k6.with_email_check(k6.functional_result(k6.run_job(ctx, "functional", "functional.js", 180)),
                                        k6.email_check(ctx))
                res["functional_pass_rate"] = f["pass_rate"]
            if res["all_available"]:
                # V4: the L7 intent check must flag the injected case (otherwise it cannot judge a repair)
                res["l7_on_case"] = intent.check(ctx, d / "manifests.yaml", meta)
            res["pods"] = kind.pods(ctx, NAMESPACE)
        finally:
            kind.delete_cluster(ctx)
        res["v3_deploys"] = bool(res.get("dry_run_ok") and res.get("all_available"))
        l7 = res.get("l7_on_case", {})
        res["v4_l7_flags_case"] = v4_flags(l7)
    res["valid"] = (res["v1_flagged"] and res["v1_targets_present"] and not res["unexpected_new_findings"]
                    and res["v2_gold_clean_for_targets"] and res.get("v3_deploys", not deploy)
                    and res.get("v4_l7_flags_case", not deploy))
    (d / "validation.json").write_text(json.dumps(res, indent=1), encoding="utf-8", newline="\n")
    return res
