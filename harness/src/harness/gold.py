"""Build the gold manifest set from upstream Online Boutique, reproducibly.

upstream YAML  --(verify sha256)-->  drop workloads  -->  pin images by digest  -->  app/gold/manifests.yaml

No hand edits to the output: every change is a step here (and later, a hardening patch), so the gold
app can be rebuilt byte-for-byte from the repo.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
GOLD = ROOT / "app" / "gold"
UPSTREAM = GOLD / "upstream" / "kubernetes-manifests.v0.10.7.yaml"
LOCK = GOLD / "images.lock.json"
OUT = GOLD / "manifests.yaml"


def _containers(doc: dict) -> list[dict]:
    spec = doc.get("spec", {}).get("template", {}).get("spec", {})
    return spec.get("initContainers", []) + spec.get("containers", [])


def pin_image(image: str, lock: dict[str, str]) -> str:
    ref = image.split("@")[0]
    if ref not in lock:
        raise KeyError(f"image not in lock file: {ref}")
    return f"{ref}@{lock[ref]}"


def build(upstream: Path = UPSTREAM, lock_path: Path = LOCK) -> list[dict]:
    lock = json.loads(lock_path.read_text(encoding="utf-8"))
    raw = upstream.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != lock["upstream_sha256"]:
        raise ValueError(f"upstream sha256 mismatch: {digest}")

    dropped = set(lock["dropped_workloads"])
    docs = []
    for doc in yaml.safe_load_all(raw):
        if not doc or doc["metadata"]["name"] in dropped:
            continue
        for c in _containers(doc):
            c["image"] = pin_image(c["image"], lock["images"])
        docs.append(doc)
    return docs


NAMESPACE = "boutique"
UID = 10001  # kube-score / Checkov CKV_K8S_40 want a UID > 10000
NETPOL_DIR = GOLD / "upstream" / "network-policies"  # upstream v0.10.7 component, loadgenerator excluded
DROPPED_OBJECTS = {"frontend-external"}  # LoadBalancer Service; k6 reaches frontend in-cluster
EPHEMERAL = {"requests": "64Mi", "limits": "512Mi"}


def startup_probe(liveness: dict) -> dict:
    """Same check as liveness, but up to 60 s (30 x 2 s) for a cold start before liveness takes over.

    Removes cold-start liveness kills (seen on emailservice/recommendationservice) so the baseline is clean.
    """
    handler = {k: v for k, v in liveness.items() if k in ("grpc", "httpGet", "tcpSocket", "exec")}
    return {**handler, "periodSeconds": 2, "timeoutSeconds": 5, "failureThreshold": 30}


def harden(docs: list[dict]) -> list[dict]:
    """Hardening applied on top of upstream. Every rule here is listed in docs/decisions.md D-011."""
    ns = {"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": NAMESPACE}}
    netpols = [yaml.safe_load(p.read_text(encoding="utf-8")) for p in sorted(NETPOL_DIR.glob("*.yaml"))]

    out = [ns]
    for doc in docs + netpols:
        if doc["metadata"]["name"] in DROPPED_OBJECTS:
            continue
        doc["metadata"]["namespace"] = NAMESPACE
        if doc["kind"] == "ServiceAccount":
            doc["automountServiceAccountToken"] = False
        if doc["kind"] == "Deployment":
            pod = doc["spec"]["template"]["spec"]
            pod["automountServiceAccountToken"] = False
            psc = pod.setdefault("securityContext", {})
            psc.update(runAsUser=UID, runAsGroup=UID, fsGroup=UID, runAsNonRoot=True)
            psc["seccompProfile"] = {"type": "RuntimeDefault"}
            for c in _containers(doc):
                c["startupProbe"] = startup_probe(c["livenessProbe"])
                res = c.setdefault("resources", {})
                res.setdefault("requests", {})["ephemeral-storage"] = EPHEMERAL["requests"]
                res.setdefault("limits", {})["ephemeral-storage"] = EPHEMERAL["limits"]
        out.append(doc)
    return out


def write(docs: list[dict], out: Path = OUT) -> Path:
    header = "# GENERATED by `harness gold-build` from app/gold/upstream + images.lock.json. Do not edit.\n"
    body = yaml.safe_dump_all(docs, sort_keys=False, default_flow_style=False)
    out.write_text(header + body, encoding="utf-8", newline="\n")
    return out
