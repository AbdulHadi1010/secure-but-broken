"""Every number the paper text uses, as LaTeX macros (paper/numbers.tex), generated from the analysis outputs.
The paper never types a number: it writes \\WzeroOverallSafePct etc. Re-run after any analysis change.
Usage: uv run python analysis/paper_numbers.py
Macro names: letters only (LaTeX), digits spelled out; e.g. W0 -> Wzero, C2-LLM -> CtwoLLM.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "analysis" / "out"
TEX = ROOT / "paper" / "numbers.tex"
DIGITS = {"0": "zero", "1": "one", "2": "two", "3": "three", "4": "four", "5": "five", "6": "six", "7": "seven",
          "8": "eight", "9": "nine"}


def name(*parts: str) -> str:
    s = "".join(p[:1].upper() + p[1:] for part in parts for p in re.split(r"[^A-Za-z0-9]+", part) if p)
    return re.sub(r"\d", lambda m: DIGITS[m.group()], s)


def emit(macros: dict, key: str, value) -> None:
    if key in macros:
        raise ValueError(f"duplicate macro {key}")
    if not re.fullmatch(r"[A-Za-z]+", key):
        raise ValueError(f"macro name must be letters only: {key}")
    macros[key] = value


def prop(macros, base, d):
    emit(macros, base + "K", d["k"])
    emit(macros, base + "N", d["n"])
    emit(macros, base + "Pct", f"{100 * d['p']:.1f}")
    emit(macros, base + "Lo", f"{100 * d['ci95'][0]:.1f}")
    emit(macros, base + "Hi", f"{100 * d['ci95'][1]:.1f}")


def pval(p: float) -> str:
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def main() -> None:
    m: dict = {}
    for w in ("W0", "W1"):
        r = json.loads((OUT_DIR / f"p7-results-{w}.json").read_text(encoding="utf-8"))
        W = name(w)
        emit(m, W + "Chains", r["n_chains"])
        for k, d in r["overall"].items():
            prop(m, W + "Overall" + name(k), d)
        for k, d in r["c0_scanner_only_view"].items():
            prop(m, W + "CzeroView" + name(k), d)
        for section in ("by_model", "by_condition", "by_type"):
            for g, dd in r[section].items():
                for k, d in dd.items():
                    prop(m, W + name(g) + name(k), d)
        for k, t in {**r["rq4_primary"], **r["rq4_secondary"]}.items():
            b = W + name(k.replace(" vs ", " Vs "))
            emit(m, b + "Pairs", t["n_pairs"])
            emit(m, b + "SafeA", t["safe_a"])
            emit(m, b + "SafeB", t["safe_b"])
            emit(m, b + "Aonly", t["a_only"])
            emit(m, b + "Bonly", t["b_only"])
            emit(m, b + "Rd", f"{100 * t['risk_difference']:+.1f}")
            emit(m, b + "RdLo", f"{100 * t['rd_ci95'][0]:+.1f}")
            emit(m, b + "RdHi", f"{100 * t['rd_ci95'][1]:+.1f}")
            emit(m, b + "P", pval(t["p"]))
            if "p_holm" in t:
                emit(m, b + "Pholm", pval(t["p_holm"]))
        h = r["h_fc"]
        emit(m, W + "HfcBcBreaking", h["classes_bc"]["breaking"])
        emit(m, W + "HfcBcClean", h["classes_bc"]["clean"])
        emit(m, W + "HfcAbreaking", h["class_a"]["breaking"])
        emit(m, W + "HfcAclean", h["class_a"]["clean"])
        emit(m, W + "HfcP", pval(h["p"]))
        for c, e in r["rq4_effort"].items():
            b = W + "Effort" + name(c)
            emit(m, b + "Iterations", f"{e['mean_iterations']:.2f}")
            emit(m, b + "TokensPerSafe", f"{e['tokens_per_safe_fix']:,.0f}")
            emit(m, b + "UsdPerSafe", f"{e['usd_per_safe_fix']:.3f}")
        for k, t in r["rq3_tests"].items():
            emit(m, W + "Rqthree" + name(k) + "P", "-" if t["p"] is None else pval(t["p"]))
    reg = json.loads((OUT_DIR / "p7-regression.json").read_text(encoding="utf-8"))
    for scope, rows in reg.items():
        for row in rows:
            if row["odds_ratio"] is None:
                continue
            term = re.sub(r"C\((\w+), Treatment\('[^']*'\)\)\[T\.([^\]]+)\]", r"\1 \2", row["term"])
            b = "Reg" + name(scope) + name(term)
            emit(m, b + "Or", f"{row['odds_ratio']:.2f}")
            emit(m, b + "OrLo", f"{row['or_95'][0]:.2f}")
            emit(m, b + "OrHi", f"{row['or_95'][1]:.2f}")
    p8 = json.loads((OUT_DIR / "p8-agreement.json").read_text(encoding="utf-8"))
    a = p8["agreement"]
    prop(m, "Peight" + "Agree", a)
    emit(m, "PeightKappa", f"{p8['cohen_kappa']:.2f}")
    for k, d in p8["strata"].items():
        emit(m, "Peight" + name(k) + "K", d["k"])
        emit(m, "Peight" + name(k) + "N", d["n"])
    TEX.parent.mkdir(exist_ok=True)
    lines = ["% GENERATED by analysis/paper_numbers.py from analysis/out/*.json - do not edit by hand."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
    TEX.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(m)} macros -> {TEX}")


if __name__ == "__main__":
    main()
