"""Paper tables generated from the data (no hand-typed numbers):
  paper/types_table.tex    the six misconfiguration types: fix class, Pod Security Standards level, target scanner
                           rules (from cases/*/meta.json), static intent policies and runtime probe (frozen definitions
                           in docs/protocol.md and policies/intent/README.md, fixed before any repair was run)
  paper/verdict_table.tex  final verdicts per repair condition for both prompt wordings (from the P7 chain table)
Usage: uv run python analysis/paper_tables.py
"""

from __future__ import annotations

import csv
import glob
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
CHAINS = sorted(glob.glob(str(ROOT / "analysis" / "out" / "p7-20261014-W0-std*chains.csv")))[0]

# Frozen definitions (docs/protocol.md "Types" table; policies/intent/README.md, fixed 2026-10-04 before any repair).
TYPES = [
    ("privileged", "privileged container", "Baseline", "disallow-privileged-containers",
     r"bounding set not full (\texttt{CapBnd})"),
    ("allow-privilege-escalation", r"\texttt{allowPrivilegeEscalation}", "Restricted", "disallow-privilege-escalation",
     r"\texttt{NoNewPrivs} = 1"),
    ("added-capabilities", "added capability", "Baseline", "disallow-capabilities(-strict)",
     r"injected bit absent from \texttt{CapBnd}"),
    ("run-as-root", "running as root", "Restricted", "require-run-as-non-root(-user)", "effective UID $\\neq 0$"),
    ("missing-limits", "missing resource limits", "--", "require-pod-requests-limits",
     "running container has CPU and memory limits"),
    ("netpol", "missing NetworkPolicy", "--", "--", "connection from another namespace blocked"),
]
VERDICTS = [("SAFE_FIX", "Safe"), ("BREAKING_FIX", "Breaking"), ("DECEPTIVE_FIX", "Deceptive"),
            ("BREAKING_AND_DECEPTIVE", "Br.+Dec."), ("NOT_FIXED", "Not fixed"), ("INVALID_OUTPUT", "Invalid")]
CONDS = ["C0", "C1", "C2-LLM", "C2-template"]


def types_table() -> None:
    metas = [json.load(open(p, encoding="utf-8")) for p in glob.glob(str(ROOT / "cases" / "*" / "meta.json"))]
    by_type = defaultdict(list)
    for m in metas:
        by_type[m["type"]].append(m)
    lines = [r"% generated by analysis/paper_tables.py; do not edit",
             r"\begin{table}[t]\centering\small",
             r"\caption{Misconfiguration types (three services each, 18 cases). Fix class: (a) flip a setting, "
             r"(b) choose an application-fitting value, (c) needs the application's call structure. Target rules are "
             r"the scanner rules (Checkov, KICS, kube-score) that flag the injected case; L7 passes only if the static "
             r"policy and the runtime probe both pass and no other control was weakened.}\label{tab:types}",
             r"\resizebox{\linewidth}{!}{%", r"\begin{tabular}{llcllp{4.4cm}}\toprule",
             r"Type & Services & Class & PSS & Static intent policy (Kyverno) & Runtime probe: intent met when \\ \midrule"]
    for key, label, pss, static, probe in TYPES:
        ms = by_type[key]
        services = ", ".join(sorted(m["service"].replace("service", "") for m in ms))
        classes = sorted({m["fix_class"] for m in ms})
        lines.append(f"{label} & {services} & ({'/'.join(classes)}) & {pss} & {static} & {probe} \\\\")
    lines += [r"\bottomrule\end{tabular}}\end{table}"]
    (PAPER / "types_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("types_table.tex:", sum(len(v) for v in by_type.values()), "cases")


def verdict_table() -> None:
    rows = list(csv.DictReader(open(CHAINS, encoding="utf-8")))
    cnt = Counter((r["wording"], r["condition"], r["final_verdict"]) for r in rows)
    tot = Counter((r["wording"], r["condition"]) for r in rows)
    lines = [r"% generated by analysis/paper_tables.py from the P7 chain table; do not edit",
             r"\begin{table}[t]\centering\small",
             r"\caption{Final verdict of every repair chain by condition and prompt wording (W0 primary). Each "
             r"condition has 180 chains per wording (18 cases $\times$ 3 models, 3 repeats; 5 for NetworkPolicy).}"
             r"\label{tab:verdicts}",
             r"\begin{tabular}{ll" + "r" * (len(VERDICTS) + 1) + r"}\toprule",
             "Wording & Condition & " + " & ".join(v[1] for v in VERDICTS) + r" & Chains \\ \midrule"]
    for w in ("W0", "W1"):
        for i, c in enumerate(CONDS):
            cells = [str(cnt[(w, c, v)]) for v, _ in VERDICTS]
            lines.append(f"{w if i == 0 else ''} & {c} & " + " & ".join(cells) + f" & {tot[(w, c)]} \\\\")
        if w == "W0":
            lines.append(r"\midrule")
    lines += [r"\bottomrule\end{tabular}\end{table}"]
    (PAPER / "verdict_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("verdict_table.tex:", len(rows), "chains")


def method_numbers() -> None:
    """Load-test band thresholds from the active baseline (app/baseline/ACTIVE), as macros."""
    label = (ROOT / "app" / "baseline" / "ACTIVE").read_text(encoding="utf-8").strip()
    band = json.load(open(ROOT / "app" / "baseline" / f"{label}.json", encoding="utf-8"))["band"]
    p95_max = band["p95_ms"]["mean"] + 3 * band["p95_ms"]["sd"]
    err_max = band["error_rate"]["max"] + 0.01
    m = {"BandRuns": band["n_runs"], "BandPNinetyFiveMax": f"{p95_max:.1f}", "BandErrorMaxPct": f"{100 * err_max:.1f}"}
    lines = ["% generated by analysis/paper_tables.py from the active baseline; do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
    (PAPER / "method_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("method_numbers.tex:", m)


if __name__ == "__main__":
    types_table()
    verdict_table()
    method_numbers()
