"""LaTeX macros with the literature-review counts (from docs/lit-review/prisma-counts.json written by prisma_figure.py,
and from the extraction file), so the related-work text contains no hand-typed numbers.
Writes paper/lit_numbers.tex.
Usage: uv run --group analysis python scripts/lit/prisma_figure.py && uv run python scripts/lit/lit_numbers.py
"""

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LR = ROOT / "docs" / "lit-review"
sys.path.insert(0, str(Path(__file__).resolve().parent))
from gap_table import first  # noqa: E402


def main() -> None:
    c = json.loads((LR / "prisma-counts.json").read_text(encoding="utf-8"))
    with (LR / "fulltext-extraction.tsv").open(encoding="utf-8") as f:
        inc = [r for r in csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE) if r["ft_decision"].startswith("include")]
    dep = sum(first(r["deploys"]) == "yes" for r in inc)
    beh = sum(first(r["app_behaviour"]) == "yes" for r in inc)
    sec = sum(first(r["runtime_security_intent"]) == "yes" for r in inc)
    both = sum(first(r["deploys"]) == "yes" and first(r["app_behaviour"]) == "yes" for r in inc)
    all3 = sum(all(first(r[k]) == "yes" for k in ("deploys", "app_behaviour", "runtime_security_intent")) for r in inc)
    m = {"LitRecords": c["unique_db"] + c["snowballing"], "LitSnowball": c["snowballing"], "LitFullTextSought": c["sought"],
         "LitFullTextAssessed": c["assessed"], "LitNotRetrieved": c["not_retrieved"], "LitIncluded": c["included"],
         "LitDeploys": dep, "LitAppBehaviour": beh, "LitRuntimeIntent": sec, "LitDeployAndBehaviour": both,
         "LitAllThree": all3}
    for k, v in c["per_database"].items():
        m["LitDb" + "".join(ch for ch in k if ch.isalpha())] = v
    lines = ["% generated by scripts/lit/lit_numbers.py; do not edit"] + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
    (ROOT / "paper" / "lit_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(m)


if __name__ == "__main__":
    main()
