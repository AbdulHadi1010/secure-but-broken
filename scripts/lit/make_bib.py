"""Build paper/references.bib for every \\cite{Rxxxx} key in paper/*.tex from docs/lit-review/records.csv.

Keys are record ids, so every citation traces back to the screening and extraction files. Title, year, venue, DOI
and arXiv id come from records.csv; author lists are looked up in OpenAlex (by DOI, else arXiv DOI, else title) and
cached in docs/lit-review/bib-authors.json so a rebuild does not depend on the network.
Usage: uv run python scripts/lit/make_bib.py
"""

from __future__ import annotations

import csv
import json
import re
import sys
import urllib.parse
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import search  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
LR = ROOT / "docs" / "lit-review"
CACHE = LR / "bib-authors.json"


def authors(rec: dict, cache: dict) -> list[str]:
    if rec["rec_id"] in cache:
        return cache[rec["rec_id"]]
    w = {}
    for doi in [rec["doi"]] + ([f"10.48550/arxiv.{rec['arxiv']}"] if rec["arxiv"] else []):
        if doi:
            try:
                w = json.loads(search._get("https://api.openalex.org/works/doi:" + urllib.parse.quote(doi)))
                break
            except Exception:  # noqa: BLE001
                continue
    if not w:
        d = json.loads(search._get("https://api.openalex.org/works?" + urllib.parse.urlencode(
            {"search": rec["title"][:200], "per-page": 1})))
        w = (d.get("results") or [{}])[0]
    names = [a["author"]["display_name"] for a in w.get("authorships", [])]
    cache[rec["rec_id"]] = names
    return names


def esc(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def main() -> None:
    keys = sorted({k.strip() for p in (ROOT / "paper").glob("*.tex")
                   for grp in re.findall(r"\\cite\{([^}]*)\}", p.read_text(encoding="utf-8")) for k in grp.split(",")})
    recs = {r["rec_id"]: r for r in csv.DictReader((LR / "records.csv").open(encoding="utf-8"))}
    cache = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() else {}
    overrides = json.loads((LR / "bib-overrides.json").read_text(encoding="utf-8"))
    out = []
    for k in keys:
        r = recs[k]
        names = authors(r, cache)
        kind = "article" if r["type"] in ("article", "journal-article") else "inproceedings"
        if r["arxiv"] and ("arxiv" in r["venue"].lower() or not r["venue"]):
            kind = "misc"
        fields = {"title": "{" + esc(r["title"]) + "}", "author": " and ".join(esc(n) for n in names) or "{Anonymous}",
                  "year": r["year"]}
        if kind == "article":
            fields["journal"] = esc(r["venue"])
        elif kind == "inproceedings":
            fields["booktitle"] = esc(r["venue"] or "Proceedings")
        else:
            fields["howpublished"] = f"arXiv:{r['arxiv']}"
        if r["doi"] and not r["doi"].lower().startswith("10.48550"):
            fields["doi"] = r["doi"]
        ov = overrides.get(k, {})
        if ov:  # documented corrections (docs/lit-review/bib-overrides.json)
            kind = ov.get("kind", kind)
            if kind in ("inproceedings", "mastersthesis"):
                fields.pop("howpublished", None)
                fields.pop("journal", None)
            if kind == "mastersthesis":
                fields.pop("booktitle", None)
            if kind == "misc":
                fields.pop("journal", None)
                fields.pop("booktitle", None)
            for f in ("journal", "booktitle", "howpublished", "school", "doi"):
                if f in ov:
                    fields[f] = esc(ov[f]) if f != "doi" else ov[f]
            if "title" in ov:
                fields["title"] = "{" + esc(ov["title"]) + "}"
        out.append(f"@{kind}{{{k},\n" + ",\n".join(f"  {f} = {{{v}}}" for f, v in fields.items()) + "\n}\n")
    CACHE.write_text(json.dumps(cache, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    (ROOT / "paper" / "references.bib").write_text("% generated by scripts/lit/make_bib.py; do not edit\n" + "\n".join(out),
                                                   encoding="utf-8", newline="\n")
    print(len(keys), "entries; without authors:", [k for k in keys if not cache.get(k)])


if __name__ == "__main__":
    main()
