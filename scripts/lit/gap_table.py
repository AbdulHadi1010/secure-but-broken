"""Gap table for the related-work section, generated from docs/lit-review/fulltext-extraction.tsv.

For every included study: artefact, task, deploys, application behaviour, runtime security intent, feedback loop.
Each yes/partial/no cell is the first word of the extraction cell, which was written from a quoted passage of the
paper (column 'evidence'). Writes docs/lit-review/gap-table.md and prints the column totals.
Usage: uv run python scripts/lit/gap_table.py
"""

import csv
import sys
from collections import Counter
from pathlib import Path

LR = Path(__file__).resolve().parents[2] / "docs" / "lit-review"
COLS = [("deploys", "Deploys"), ("app_behaviour", "App behaviour"), ("runtime_security_intent", "Runtime security intent"),
        ("feedback_loop", "Feedback loop")]


def first(v: str) -> str:
    return v.split(" ")[0].split(":")[0].strip("(),;") or "-"


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    titles = {r["rec_id"]: r for r in csv.DictReader((LR / "screening.csv").open(encoding="utf-8"))}
    rows = [r for r in csv.DictReader((LR / "fulltext-extraction.tsv").open(encoding="utf-8"), delimiter="\t",
                                                quoting=csv.QUOTE_NONE)
            if r["ft_decision"].startswith("include")]
    out = ["# Gap table (generated by scripts/lit/gap_table.py; do not edit by hand)", "",
           "| Record | Year | Title | Artefact | Task | " + " | ".join(c[1] for c in COLS) + " |",
           "|" + "---|" * (5 + len(COLS))]
    for r in sorted(rows, key=lambda r: (titles[r["rec_id"]]["year"], r["rec_id"])):
        t = titles[r["rec_id"]]
        cells = [r["rec_id"], t["year"], t["title"][:70].replace("|", "/"), r["artefact"][:40].replace("|", "/"),
                 r["task"][:40].replace("|", "/")] + [first(r[c]) for c, _ in COLS]
        out.append("| " + " | ".join(cells) + " |")
    tot = {c: Counter(first(r[c]) for r in rows) for c, _ in COLS}
    all3 = [r["rec_id"] for r in rows if all(first(r[c]) == "yes" for c in ("deploys", "app_behaviour",
                                                                           "runtime_security_intent"))]
    out += ["", f"Included studies: {len(rows)}"] + [f"- {lab}: {dict(tot[c])}" for c, lab in COLS]
    out.append(f"- Deploys AND checks app behaviour AND checks security intent at runtime: {all3 or 'none'}")
    (LR / "gap-table.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(out[-(len(COLS) + 2):]))


if __name__ == "__main__":
    main()
