"""LaTeX gap table for the paper: the shortlisted closest studies (docs/lit-review/gap-shortlist.tsv) plus this study.

Short name, artefact, task and oracle labels come from the shortlist file (hand-written summaries of the extraction);
the Deploy / App behaviour / Runtime security intent / Feedback cells are the first word of the corresponding
fulltext-extraction.tsv cells (yes / partial / no), so they cannot drift from the extraction.
Writes paper/gap_table.tex.
Usage: uv run python scripts/lit/gap_table_tex.py
"""

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LR = ROOT / "docs" / "lit-review"
MARK = {"yes": r"\ding{51}", "partial": r"$\circ$", "no": "--"}
COLS = ["deploys", "app_behaviour", "runtime_security_intent"]


def first(v: str) -> str:
    return v.split(" ")[0].split(":")[0].strip("(),;").lower()


def fb(v: str) -> str:
    """Kind of feedback between attempts, from the extraction cell: runtime evidence, static checks, or none."""
    v = v.lower()
    if v.startswith("no"):
        return "--"
    if "no runtime" not in v and any(w in v for w in ("runtime", "live", "deployment error", "cluster feedback")):
        return "runtime"
    if any(w in v for w in ("static", "scanner", "validator", "validation", "verif", "formal", "diagnostic",
                            "refinement")):
        return "static"
    return "other"


def tex(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def main() -> None:
    with (LR / "fulltext-extraction.tsv").open(encoding="utf-8") as f:
        ext = {r["rec_id"]: r for r in csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE)}
    scr = {r["rec_id"]: r for r in csv.DictReader((LR / "screening.csv").open(encoding="utf-8"))}
    short = list(csv.DictReader((LR / "gap-shortlist.tsv").open(encoding="utf-8"), delimiter="\t"))
    lines = [r"% generated by scripts/lit/gap_table_tex.py from docs/lit-review/fulltext-extraction.tsv; do not edit",
             r"\begin{table*}[t]\centering\small",
             r"\caption{Closest prior work. \ding{51} yes, $\circ$ partly (see text), -- no. Feedback: what the"
             r" repairer sees between attempts.}\label{tab:gap}",
             r"\resizebox{\textwidth}{!}{%",
             r"\begin{tabular}{lllllcccl}\toprule",
             r"Study & Year & Artefact & Task & Success oracle & Deploys & App behaviour & Runtime intent & "
             r"Feedback \\ \midrule"]
    for s in short:
        e = ext[s["rec_id"]]
        assert e["ft_decision"].startswith("include"), s["rec_id"]
        cells = [MARK.get(first(e[c]), "?") for c in COLS]
        lines.append(f"{tex(s['short_name'])}~\\cite{{{s['rec_id']}}} & {scr[s['rec_id']]['year']} & {tex(s['artefact'])} & "
                     f"{tex(s['task'])} & {tex(s['success_oracle'])} & " + " & ".join(cells) + f" & {fb(e['feedback_loop'])} \\\\")
    lines += [r"\midrule",
              r"\textbf{This study} & 2026 & K8s & security repair & L1--L7 gates & \ding{51} & \ding{51} (function + load)"
              r" & \ding{51} (policy + probe) & runtime \\",
              r"\bottomrule\end{tabular}}\end{table*}"]
    (ROOT / "paper" / "gap_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(len(short), "rows -> paper/gap_table.tex")


if __name__ == "__main__":
    main()
